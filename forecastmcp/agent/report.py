def extract_report_numbers(text: str) -> list[float]:
    """Extract numerals from report text, ignoring citation tokens."""
    stripped = CITATION_RE.sub(" ", text)
    return [float(m.group(0)) for m in NUMBER_RE.finditer(stripped)]


def collect_trace_numbers(records: Iterable[dict[str, Any]]) -> list[float]:
    """Collect every number present in tool payloads (including JSON keys)."""
    numbers: list[float] = []

    def visit(value: Any) -> None:
        if isinstance(value, bool) or value is None:
            return
        if isinstance(value, (int, float)):
            numbers.append(float(value))
        elif isinstance(value, str):
            for match in NUMBER_RE.finditer(value):
                with contextlib.suppress(ValueError):
                    numbers.append(float(match.group(0)))
        elif isinstance(value, dict):
            for key, item in value.items():
                visit(key)
                visit(item)
        elif isinstance(value, (list, tuple)):
            for item in value:
                visit(item)

    for rec in records:
        visit(rec.get("payload", rec))
    return numbers


def match_number(value: float, candidates: list[float], rtol: float = 0.01,
                 atol: float = 0.05) -> bool:
    """True when ``value`` approximately equals any trace number."""
    arr = np.asarray(candidates, dtype=float)
    if arr.size == 0:
        return False
    return bool(np.any(np.abs(arr - value) <= np.maximum(atol, rtol * np.abs(arr))))


def unsupported_numbers(
    report_text: str,
    records: Iterable[dict[str, Any]],
    rtol: float = 0.01,
    atol: float = 0.05,
) -> list[float]:
    """Return report numerals that have no matching value in the trace payloads."""
    candidates = collect_trace_numbers(records)
    return [v for v in extract_report_numbers(report_text) if not match_number(v, candidates, rtol, atol)]


def unsupported_number_rate(report_text: str, records: Iterable[dict[str, Any]]) -> float:
    """Fraction of report numerals with no matching trace value (0.0 is ideal)."""
    nums = extract_report_numbers(report_text)
    if not nums:
        return 0.0
    return len(unsupported_numbers(report_text, records)) / len(nums)


def citation_coverage(report_text: str, records: Iterable[dict[str, Any]]) -> float:
    """Fraction of cited call ids that exist in the trace records."""
    known = {rec["call_id"] for rec in records}
    cited = set(CITATION_RE.findall(report_text))
    if not cited:
        return 0.0
    return len(cited & known) / len(cited)
