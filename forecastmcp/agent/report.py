"""Stakeholder-readable forecast rationale with per-number trace citations."""

from __future__ import annotations

import contextlib
import re
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import numpy as np

CITATION_RE = re.compile(r"\[call:([A-Za-z0-9_.:-]+)\]")
NUMBER_RE = re.compile(r"(?<![\w.])-?\d+(?:\.\d+)?")


def cite(call_id: str) -> str:
    """Inline citation token pointing at one trace call."""
    return f"[call:{call_id}]"


def _fmt(value: float, digits: int = 3) -> str:
    if value is None or not np.isfinite(value):
        return "n/a"
    return f"{value:.{digits}f}"


def _records_by_tool(records: Iterable[dict[str, Any]]) -> dict[str, list[dict[str, Any]]]:
    grouped: dict[str, list[dict[str, Any]]] = {}
    for rec in records:
        grouped.setdefault(rec["tool"], []).append(rec["payload"])
    return grouped


def _first(payloads: list[dict[str, Any]] | None) -> dict[str, Any] | None:
    return payloads[0] if payloads else None


def build_report(
    question: str,
    plan: Any,
    records: list[dict[str, Any]],
    unavailable_models: dict[str, str] | None = None,
) -> str:
    """Render ``report.md``.

    Every numeric claim is copied from a tool payload and followed by
    ``[call:<id>]``. The question is not echoed verbatim so that no untraced
    numeral can slip into the document.
    """
    grouped = _records_by_tool(records)
    described = _first(grouped.get("describe_series"))
    forecasts = grouped.get("forecast", [])
    backtests = grouped.get("backtest", [])
    ensemble = _first(grouped.get("ensemble_forecast"))

    lines: list[str] = []
    series_id = plan.series_id
    dataset = plan.dataset
    lines.append(f"# Forecast rationale: {series_id}")
    lines.append("")
    lines.append(
        "This note was generated by ForecastMCP's traced agent. It inspects the series, runs "
        "several forecasters, scores them on the frozen rolling-origin holdout, reconciles their "
        "disagreement, and cites the trace call behind every number."
    )
    lines.append("")

    if described:
        cid = described["call_id"]
        s = described["series"]
        lines.append("## Series context")
        lines.append(
            f"{s['series_id']} in dataset {dataset} has {s['n_obs']} observations from "
            f"{s['start']} to {s['end']} {cite(cid)}. The historical mean is "
            f"{_fmt(s['mean'])} units and the last observed value is {_fmt(s['last_value'])} "
            f"{cite(cid)}. Available covariates include "
            + ", ".join(described["covariates"][:6])
            + f" {cite(cid)}."
        )
        lines.append("")

    if ensemble:
        cid = ensemble["call_id"]
        sm = ensemble.get("summary", {})
        levels = ensemble["quantile_levels"]
        lo_level, hi_level = levels[0], levels[-1]
        lines.append("## Recommendation")
        lines.append(
            f"Use the reconciled forecast `{ensemble['model_name']}` for the "
            f"{ensemble['horizon']}-day horizon (frozen window {plan.window_id}) {cite(cid)}. "
            f"The median path averages {_fmt(sm.get('mean_point', 0.0))} units per day and ends at "
            f"{_fmt(sm.get('last_point', 0.0))} units {cite(cid)}. The central "
            f"{lo_level} to {hi_level} interval averages {_fmt(sm.get('p80_low_mean', 0.0))} to "
            f"{_fmt(sm.get('p80_high_mean', 0.0))} units {cite(cid)}. It covers "
            f"{ensemble['dates'][0]} to {ensemble['dates'][-1]} {cite(cid)}."
        )
        lines.append("")
        lines.append(
            f"Reconciliation rule that fired: `{ensemble['rule_fired']}` "
            f"{cite(cid)}. Mean pairwise quantile divergence across members was "
            f"{_fmt(ensemble['divergence']['mean_pairwise'], 4)} "
            f"(level: {ensemble['divergence']['level']}) {cite(cid)}."
        )
        lines.append("")
        weights = ensemble["weights"]
        weight_text = ", ".join(f"{name} {_fmt(w, 3)}" for name, w in weights.items())
        lines.append(f"Member weights: {weight_text} {cite(cid)}.")
        lines.append("")

    if forecasts and backtests:
        lines.append("## Candidate comparison")
        lines.append("")
        lines.append("| model | backtest WQL | MASE | coverage_80 | median-path mean | trace |")
        lines.append("|---|---|---|---|---|---|")
        bt_by_model = {b["model"]: b for b in backtests}
        for fc in forecasts:
            model = fc["forecast"]["model_name"]
            bt = bt_by_model.get(model)
            if not bt:
                continue
            m = bt["metrics"]
            lines.append(
                f"| {model} | {_fmt(m['WQL']['value'], 4)} | {_fmt(m['MASE']['value'], 4)} | "
                f"{_fmt(m['coverage_80']['value'], 3)} | "
                f"{_fmt(fc.get('summary', {}).get('median_mean', 0.0))} | "
                f"{cite(bt['call_id'])} {cite(fc['call_id'])} |"
            )
        lines.append("")
        lines.append(
            f"Backtests use {backtests[0]['n_windows']} frozen rolling-origin windows "
            f"{cite(backtests[0]['call_id'])}. Lower WQL and MASE are better; coverage_80 closer "
            "to its nominal level is better calibrated."
        )
        lines.append("")

    if ensemble and len(forecasts) >= 2:
        lines.append("## Disagreement and reconciliation")
        pairs = ensemble["divergence"]["pairs"]
        for pair, value in pairs.items():
            a, b = pair.split("|", 1)
            lines.append(
                f"- {a} vs {b}: divergence {_fmt(value, 4)} {cite(ensemble['call_id'])}"
            )
        lines.append(
            f"- Max pairwise divergence {_fmt(ensemble['divergence']['max_pairwise'], 4)} "
            f"{cite(ensemble['call_id'])}"
        )
        lines.append("")
        lines.append(
            "Vincentization averages quantiles level by level; inverse-error weighting uses each "
            "member's backtest WQL; best-on-backtest selects the lowest-WQL member. The rule and "
            "weights above record which of these fired."
        )
        lines.append("")

    if backtests:
        lines.append("## Calibration and error")
        for bt in backtests:
            m = bt["metrics"]
            lines.append(
                f"- {bt['model']}: WQL {_fmt(m['WQL']['value'], 4)}, CRPS "
                f"{_fmt(m['CRPS']['value'], 4)}, MASE {_fmt(m['MASE']['value'], 4)}, "
                f"coverage_80 {_fmt(m['coverage_80']['value'], 3)}, coverage_90 "
                f"{_fmt(m['coverage_90']['value'], 3)} {cite(bt['call_id'])}"
            )
        lines.append("")

    lines.append("## Limitations")
    lines.append(
        "Foundation-model forecasts here are zero-shot unless the selected registry entry is a "
        "fine-tuned adapter; Chronos does not consume the promotion or lead-time covariates, so "
        "any covariate use is recorded as false in the trace. Backtest scores come from a small "
        "number of frozen windows and should be read as directional, not definitive."
    )
    if unavailable_models:
        lines.append("")
        lines.append("Unavailable foundation models in this run:")
        for name, reason in unavailable_models.items():
            lines.append(f"- {name}: {reason}")
    lines.append("")
    lines.append("## Provenance")
    lines.append("")
    lines.append("| call | tool |")
    lines.append("|---|---|")
    for rec in records:
        lines.append(f"| {cite(rec['call_id'])} | {rec['tool']} |")
    lines.append("")
    lines.append(
        "All calls are replayable: `forecastmcp replay <run_id>` re-executes them from "
        "trace.jsonl and checks byte-identical outputs. The run id is recorded in the trace."
    )
    return "\n".join(lines) + "\n"


def write_report(run_dir: Path | str, text: str) -> Path:
    """Write report.md into a run directory."""
    path = Path(run_dir) / "report.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


